interface Painted {
  icon: number;
  text: string | null;
  value: string | null;
}

interface PresetRow {
  preset: CompactPreset;
  /** The chip, in the bar / in the `⋮` menu / in the bar with no icon supplied. */
  chipBar: Painted;
  chipMenu: Painted;
  chipBare: Painted;
  /** The `checkout.tier` promoted control, same three places. */
  flagBar: Painted;
  flagMenu: Painted;
  flagBare: Painted;
  /**
   * The `new-header` promoted **boolean**, in the bar, with and without an icon.
   *
   * Its own columns because a boolean is the one control with no value slot —
   * a switch announces its own state — so `"value"` and an iconless
   * `"icon-value"` would resolve to nothing at all. That is the blank-control
   * hole kit's guarantee 1 does not cover (it is about `"icon"` alone), and
   * these two columns are where the text fallback that closes it is pinned.
   */
  boolBar: Painted;
  boolBare: Painted;
}

