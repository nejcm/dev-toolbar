describe("the hard rule: a ReactNode never enters the store", () => {
  /**
   * The reason `PromotedFlag.icon` was not widened to `ReactNode`. It is copied
   * into every snapshot as `FlagView.promotedIcon`, and this store publishes on
   * a string signature — so a node there would either never publish or
   * republish on every 250 ms tick, and would sit inside the object
   * `diagnostics()` serialises, one refactor away from a circular-structure
   * throw inside a click handler. `presentation` is config in the factory
   * closure instead, and these assertions are what says so.
   */
  const RICH: PromotedFlag = {
    flagKey: "checkout.tier",
    icon: "A",
    presentation: { preset: "icon", icon: ICON, render: () => ICON, name: () => "Tier" },
  };

  const richRuntime = () =>
    createFlagsRuntime({
      flags: CATALOGUE,
      promoted: [RICH],
      onOverride: () => {},
      now: () => 0,
    });

  /**
   * Asserts *structurally* rather than by looking for `"$$typeof"` in the JSON.
   *
   * `JSON.stringify` silently drops a Symbol-valued property, and a React
   * element's `$$typeof` is a Symbol — so `JSON.stringify({ icon: <svg/> })`
   * yields a `$$typeof`-free object and throws nothing. A marker search would
   * therefore pass with an element sitting in the snapshot: it could not fail
   * for the wrong reason, which makes it not evidence. A round-trip equality
   * check and an `isValidElement` walk can both fail, so they are.
   */
  const expectNoElements = (value: unknown): void => {
    expect(isValidElement(value)).toBe(false);
    if (value !== null && typeof value === "object") {
      Object.values(value).forEach(expectNoElements);
    }
  };

  it("keeps the snapshot serialisable with a JSX icon promoted", () => {
    const runtime = richRuntime();
    const snapshot = runtime.store.peek();
    // Round-trips unchanged: nothing in here is a value `JSON.stringify` drops
    // (a Symbol, a function, an `undefined`) or rewrites.
    expect(JSON.parse(JSON.stringify(snapshot))).toEqual(snapshot);
    expectNoElements(snapshot);
    expect(JSON.stringify(snapshot)).not.toContain("presentation");
    // The string glyph is still there, and still a string; the rich one never
    // arrived.
    const view = snapshot.promoted.find((entry) => entry.key === "checkout.tier") as FlagView;
    expect(typeof view.promotedIcon).toBe("string");
    expect(view.promotedIcon).toBe("A");
    runtime.store.destroy();
  });

  it("keeps diagnostics() serialisable with a JSX icon promoted", () => {
    const runtime = richRuntime();
    runtime.applyOverride("checkout.tier", "silver");
    const diagnostics = runtime.diagnostics();
    expect(JSON.parse(JSON.stringify(diagnostics))).toEqual(diagnostics);
    expectNoElements(diagnostics);
    // The marker search is the *wrong* tool one assertion up and the right one
    // here, and the difference is `redact()`.
    //
    // On a raw snapshot, `JSON.stringify` drops a Symbol-valued property
    // outright, so `$$typeof` would be missing from the JSON of an object that
    // really does hold an element: the search could not fail, which is why the
    // snapshot is checked structurally instead.
    //
    // `diagnostics()` ends in `redact()`, which deep-walks and *stringifies*
    // the Symbol to `"[symbol]"`. A leaked element therefore arrives here as a
    // plain object — `{"$$typeof":"[symbol]","type":"svg","_owner":…}` — and
    // the structural walk above goes blind, because `isValidElement` is false
    // on every node of it and the round-trip is equal. Post-`redact()` the
    // element's own field names are exactly what survives, so they are the only
    // thing left that can fail.
    expect(JSON.stringify(diagnostics)).not.toMatch(/\$\$typeof|"_owner"|"_store"/);
    expect(JSON.stringify(diagnostics)).toContain("checkout.tier");
    runtime.store.destroy();
  });

  it("keeps the copy-recipe path serialisable with a JSX icon promoted", () => {
    const runtime = richRuntime();
    runtime.applyOverride("checkout.tier", "silver");
    // `recipeText()` is typed `string`, so this path is clean by construction;
    // the assertion is that the promoted rich icon did not reach its content.
    const recipe = runtime.recipeText();
    expect(recipe).toBe("checkout.tier = silver (was gold)");
    runtime.store.destroy();
  });

  it("does not republish when only the presentation changes", () => {
    // The mirror image of the `BUG:`-marked test in `runtime.test.ts`: the
    // presentation is not signed because it is not in the snapshot at all,
    // which is the design rather than a gap. Changing it after the factory ran
    // is not supported — build the extension once, as the factory's JSDoc says.
    const promoted: PromotedFlag = { flagKey: "checkout.tier", presentation: "icon" };
    const runtime = createFlagsRuntime({ flags: CATALOGUE, promoted: [promoted], now: () => 0 });
    const before = runtime.store.getSnapshot();
    const listener = vi.fn();
    runtime.store.subscribe(listener);
    promoted.presentation = { preset: "icon-value", icon: ICON };
    runtime.refresh();
    runtime.store.flush();
    expect(listener).not.toHaveBeenCalled();
    expect(runtime.store.getSnapshot()).toBe(before);
    expectNoElements(runtime.store.peek());
    runtime.store.destroy();
  });
});
