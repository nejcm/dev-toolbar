/**
 * `/ext/flags`' two `presentation` surfaces, against the real shell.
 *
 * Flags is the extension where the hard rule bites, so this file is as much
 * about what does *not* happen as about what the presets paint.
 *
 * 1. **Two surfaces, because a control's presentation is configured next to
 *    that control.** `FlagsOptions.presentation` is the chip;
 *    `PromotedFlag.presentation` is one promoted flag, invoked per flag. The
 *    alternative — one flags-level callback receiving `FlagsSnapshot |
 *    FlagView` — would make every consumer narrow a union to find out which
 *    control it was handed.
 * 2. **A `ReactNode` never enters the store.** This store republishes on a
 *    *string* signature, so an unsignable node either never publishes or
 *    republishes every 250 ms tick — and it would sit inside the object
 *    `diagnostics()` serialises, one refactor away from a circular-structure
 *    throw inside a click handler. `PromotedFlag.icon` therefore stays
 *    `string`, rich icons live on `PromotedFlag.presentation`, and the
 *    resolved presentations reach `ui.tsx` as props from the factory closure.
 *    "the store never sees a node" below is the evidence.
 * 3. **The hand-written chip stays hand-written.** This chip has no dot and
 *    the kit `Chip` always renders one, so it is not routed through `Chip`;
 *    what it gained is kit's `renderCompactParts` slotting into the span it
 *    already had. The default literals below are the proof that slotted in
 *    byte-for-byte.
 *
 * Every literal here was generated by capture from a mounted toolbar, then
 * diffed against the same capture taken before this change. Regenerate them
 * only against a deliberate, documented change to flags' bar DOM: every
 * consumer's CSS and every Playwright selector reads these attributes.
 *
 * [dev-toolbar/plans/bar-presentation-icons-v1 §5]
 */
