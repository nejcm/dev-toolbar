describe("the back-compat string icon", () => {
  /**
   * `PromotedFlag.icon` stays `string` on purpose — widening it to `ReactNode`
   * is what would put an element in the snapshot. It keeps the bare
   * `aria-hidden` span it has always rendered rather than moving into `Glyph`,
   * because moving it would change the default bytes; what it gained is a
   * place in the icon slot, so it survives a preset instead of vanishing.
   */
  it("fills the icon slot when no presentation icon was supplied", () => {
    const item = barItem(promotedWith("checkout.tier", "icon", { icon: "A" }));
    const button = promotedOf(item, "checkout.tier");
    // Guarantee 1 does *not* fire: there is an icon, it is just a string one.
    expect(promotedText(button)).toBeNull();
    expect(countIn(button, '[data-dtb-part="flag-promoted-icon"]')).toBe(0);
    expect(
      button.querySelector(":scope > span[aria-hidden]:not([data-dtb-part])")?.textContent,
    ).toBe("A");
  });

  it("yields to a presentation icon rather than painting both", () => {
    const item = barItem(
      promotedWith("checkout.tier", { preset: "icon", icon: ICON }, { icon: "A" }),
    );
    const button = promotedOf(item, "checkout.tier");
    expect(countIn(button, '[data-dtb-part="flag-promoted-icon"]')).toBe(1);
    expect(button.textContent).toBe("");
  });

  it.each([
    ["false, from a && guard", false],
    ["true", true],
    ["an empty string", ""],
  ])("fills the slot when a rich icon declines with %s", (_name, value) => {
    // One rule, both suppliers. "Declines" is `hasPaintableIcon`, so a rich
    // `icon: (v) => v.overridden && <I />` returning `false` falls back to the
    // legacy glyph exactly as `undefined` does — rather than blocking the
    // fallback *and* counting as an icon, which would have painted an empty
    // span and suppressed guarantee 1 under `preset: "icon"`.
    const button = promotedOf(
      barItem(
        promotedWith(
          "checkout.tier",
          { preset: "icon", icon: () => value as never },
          { icon: "A" },
        ),
      ),
      "checkout.tier",
    );
    expect(promotedText(button)).toBeNull();
    expect(countIn(button, '[data-dtb-part="flag-promoted-icon"]')).toBe(0);
    expect(
      button.querySelector(":scope > span[aria-hidden]:not([data-dtb-part])")?.textContent,
    ).toBe("A");
  });

  it('does not fill the icon slot with "", which would leave the control blank', () => {
    // The other half of the same rule. `""` is not an icon, so `hasIcon` is
    // false and kit's guarantee 1 fires: an icon-only preset with no icon
    // paints text. Treated as present instead, `"icon"` would resolve to
    // icon-only, paint an empty `aria-hidden` span for it, and leave a switch
    // that is a bare dot with `textContent === ""` — the exact hole guarantee 1
    // exists to close.
    const button = promotedOf(
      barItem(promotedWith("checkout.tier", "icon", { icon: "" })),
      "checkout.tier",
    );
    expect(button.querySelector(":scope > span[aria-hidden]:not([data-dtb-part])")).toBeNull();
    expect(countIn(button, '[data-dtb-part="flag-promoted-icon"]')).toBe(0);
    expect(promotedText(button)).toBe("checkout.tier");
    expect(button.textContent).not.toBe("");
  });

  it("is dropped by a preset that names no icon", () => {
    const button = promotedOf(
      barItem(promotedWith("checkout.tier", "label", { icon: "A" })),
      "checkout.tier",
    );
    expect(button.querySelector(":scope > span[aria-hidden]:not([data-dtb-part])")).toBeNull();
    expect(promotedText(button)).toBe("checkout.tier");
  });
});

